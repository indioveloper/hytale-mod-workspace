import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, basename } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tree = JSON.parse(readFileSync(resolve(root, '.build/reference/tree.json'), 'utf8'));
const paths = tree.tree.map(entry => entry.path).filter(path => /\.(png|tga)$/.test(path) && !path.includes('_mers.'));
const items = {};
for (const path of paths.filter(path => path.startsWith('resource_pack/textures/items/'))) {
  const key = basename(path).replace(/\.(png|tga)$/, '');
  items[key] = path.replace('resource_pack/', '').replace(/\.(png|tga)$/, '');
}
const effects = {};
for (const path of paths.filter(path => /^resource_pack\/textures\/ui\/\w+_effect.png$/.test(path))) {
  effects[basename(path).replace('_effect.png', '')] = path.replace('resource_pack/', '').replace('.png', '');
}
// Generated metadata only; vanilla bitmap assets remain in Minecraft, not in this repository.
writeFileSync(resolve(root, 'behavior_pack/scripts/vanilla-icons.js'),
  `// Mojang/bedrock-samples tree ${tree.sha}. Generated by tools/Generate-IconIndex.mjs.\n` +
  `export const ITEM_ICONS = ${JSON.stringify(items, null, 2)};\nexport const EFFECT_ICONS = ${JSON.stringify(effects, null, 2)};\n`);
console.log(`Indexed ${Object.keys(items).length} item icons and ${Object.keys(effects).length} effect icons.`);
